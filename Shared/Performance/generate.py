"""Generate both clients from one menu catalog; --check detects drift."""
from pathlib import Path
import json,sys
here=Path(__file__).resolve().parent
catalog=json.loads((here/'workspaces.json').read_text())
encoded=json.dumps(catalog,ensure_ascii=False,separators=(',',':'))
objc='// Generated by Shared/Performance/generate.py.\nstatic NSArray *SharedMidiWorkspaceCatalog(void) {\n    static NSArray *catalog; static dispatch_once_t once;\n    dispatch_once(&once, ^{ catalog=[NSJSONSerialization JSONObjectWithData:[@'+json.dumps(encoded,ensure_ascii=False)+' dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil]; });\n    return catalog;\n}\n'
outputs={here/'WorkspaceCatalog.generated.h':objc,here.parent/'PhoneControl/Web/performance-catalog.js':'// Generated from Shared/Performance/workspaces.json.\nwindow.ThreeEWorkspaces='+encoded+';\n'}
for path,content in outputs.items():
    if '--check' in sys.argv: assert path.read_text()==content,str(path)+' needs regeneration'
    else:path.write_text(content)
