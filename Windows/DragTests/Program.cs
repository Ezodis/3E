using ThreeFingerDragOnWindows.threefingerdrag;

int checks = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); Console.WriteLine("PASS: " + name); checks++; }
bool acceptDown = false, acceptUp = true;
var events = new List<string>();
var drag = new DragButtonState(() => { events.Add("down"); return acceptDown; }, () => { events.Add("up"); return acceptUp; });
Check(!drag.Begin(0, 500) && !drag.Held, "Rejected mouse-down never creates a phantom drag");
acceptDown = true;
Check(drag.Begin(10, 500) && drag.Held, "A gesture retries successfully after input becomes available");
Check(drag.Begin(20, 500) && events.Count == 2, "An active gesture does not press the button twice");
drag.Refresh(400, 500);
Check(!drag.Expire(510) && drag.Held, "An old queued timer cannot release a refreshed gesture");
Check(drag.Expire(900) && !drag.Held && events.Last() == "up", "The current release deadline releases the button");
Check(drag.Begin(1000, 500) && !drag.Expire(1100) && drag.Held, "A previous gesture's timer cannot release a new hold");
acceptUp = false;
Check(!drag.End() && !drag.Held && drag.ReleasePending, "Rejected release is retained for recovery");
int beforeRetry = events.Count;
Check(!drag.Begin(1200, 500) && events.Count == beforeRetry + 1 && events.Last() == "up", "A pending release blocks a new press until it succeeds");
acceptUp = true;
Check(drag.Begin(1300, 500) && events.TakeLast(2).SequenceEqual(new[]{"up","down"}), "Recovery releases the old button before starting a new drag");
Check(drag.Expire(1800) && !drag.Held, "A press without further contacts still expires");
int completedEvents = events.Count;
Check(drag.End() && events.Count == completedEvents, "Ending an already released gesture injects no extra input");
var handler=new ThreeFingerDragOnWindows.touchpad.HandlerWindow();
var contacts=new ThreeFingerDragOnWindows.touchpad.ContactsManager(handler);
ThreeFingerDragEngine.utils.TouchpadContact Finger(int id,bool active=true)=>new(id,id*100,200,active);
contacts.ReceiveTouchpadContacts((IntPtr)1,new(){Finger(1),Finger(2)},4);
Check(handler.Frames.Count==0,"Partial HID report waits for the other contacts");
contacts.ReceiveTouchpadContacts((IntPtr)1,new(){Finger(3),Finger(4)},0);
Check(handler.Frames.Single().Length==4,"Split HID report produces one complete four-finger frame");
contacts.ReceiveTouchpadContacts((IntPtr)1,new(){Finger(1,false),Finger(2,false),Finger(3,false),Finger(4,false)},0);
Check(handler.Frames.Last().Length==0,"Final Tip Switch release reaches gesture engine instead of becoming a partial report");
int frameCount=handler.Frames.Count;
contacts.ReceiveTouchpadContacts((IntPtr)1,new(){Finger(1)},4);
contacts.ReceiveTouchpadContacts((IntPtr)1,new(){Finger(2)},4);
Check(handler.Frames.Count==frameCount,"Missing packets never manufacture four fingers");
contacts.ReceiveTouchpadContacts((IntPtr)2,new(){Finger(3),Finger(4),Finger(5)},3);
Check(handler.Frames.Last().Select(p=>p.ContactId).SequenceEqual(new[]{3,4,5}),"Device change discards an unfinished frame from the old touchpad");
contacts.ReceiveTouchpadContacts((IntPtr)2,new(),0);
Check(handler.Frames.Last().Length==0,"Explicit empty report releases gestures");
contacts.ReceiveTouchpadContacts((IntPtr)2,new(){Finger(1,false),Finger(2),Finger(3),Finger(4)},4);
Check(handler.Frames.Last().Length==3,"Lifted HID slots do not count as a fourth finger");
Console.WriteLine($"{checks} drag and touchpad recovery checks passed.");
